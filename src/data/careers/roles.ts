type RoleInput = Pick<CareerRole, 'id' | 'name' | 'domainSlug' | 'description' | 'skills' | 'tools' | 'responsibilities' | 'projects' | 'interviewTopics'> & { programming?: LearningLevel; mathematics?: LearningLevel }
function role({ id, name, domainSlug, description, skills, tools, responsibilities, projects, interviewTopics, programming, mathematics }: RoleInput): CareerRole {
  const domain = careerDomains.find(item => item.slug === domainSlug)
  if (!domain) throw new Error(`Unknown career domain: ${domainSlug}`)
  return { id, slug:id, name, domainSlug, description, skills, tools, responsibilities, projects, interviewTopics,
    subjects:domain.subjects, technologies:technologies[domainSlug] ?? [], programming:programming ?? domain.programming, mathematics:mathematics ?? domain.mathematics,
    roadmap:[
      {title:'Foundations',description:`Study ${domain.subjects.slice(0,3).join(', ')} and connect each idea to a small example.`},
      {title:'Core Skills',description:`Practice ${skills.slice(0,3).join(', ')}. Keep notes on mistakes and trade-offs.`},
      {title:'Tools',description:`Use ${tools.slice(0,2).join(' and ')} to build, inspect and test a small implementation.`},
      {title:'Projects & Interview Preparation',description:`Try this project: ${projects[0]} Explain your design and revisit ${interviewTopics.slice(0,3).join(', ')}.`},
    ] }
}

