import { readFileSync, writeFileSync } from 'node:fs'

const source = readFileSync(new URL('../src/config/academic.ts', import.meta.url), 'utf8')
const value = Number(source.match(/export const CURRENT_P1_BATCH = (\d+)/)?.[1])
if (!Number.isInteger(value) || value < 2 || value > 99) throw new Error('Invalid CURRENT_P1_BATCH')
const sql = `-- Generated by npm run db:academic from src/config/academic.ts. Do not edit.\ninsert into public.academic_config (id, current_p1_batch)\nvalues (true, ${value})\non conflict (id) do update set current_p1_batch = excluded.current_p1_batch;\n`
writeFileSync(new URL('../supabase/migrations/002_academic_cycle.sql', import.meta.url), sql)
console.log(`Generated academic-cycle SQL for P1 batch ${value}.`)
